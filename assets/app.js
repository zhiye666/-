function skillStats() {
  const total = SKILL_TREE.reduce((s, lv) => s + lv.items.length, 0);
  let done = 0;
  const byLv = SKILL_TREE.map((lv, li) => {
    let d = 0;
    lv.items.forEach((it, ii) => { if (DB.data.skills[li + '|' + ii]) d++; });
    done += d;
    return { done: d, total: lv.items.length, pct: lv.items.length ? Math.round(d / lv.items.length * 100) : 0 };
  });
  return { total, done, pct: total ? Math.round(done / total * 100) : 0, byLv };
}

