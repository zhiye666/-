const DB_KEY = 'cad_fire_study_v1';

const DB = {
  data: null,
  default() {
    return {
      skills: {},                 // { "lv|idx": true }
      notes: [],                  // 复盘/规范笔记
      mistakes: [],               // 错题
      exam: { yx: '', cz: '' },   // 考试日期
      logs: [],                   // 每周日志
      quiz: { answered: 0, correct: 0 },   // 测验统计
      outcheck: {},               // 出图自查勾选
      updatedAt: ''
    };
  },
  load() {
    try {
      const raw = localStorage.getItem(DB_KEY);
      this.data = raw ? Object.assign(this.default(), JSON.parse(raw)) : this.default();
      this.data.quiz = Object.assign({ answered: 0, correct: 0 }, this.data.quiz);
    } catch (e) {
      this.data = this.default();
    }
    return this.data;
  },
  save() {
    this.data.updatedAt = new Date().toISOString();
    try {
      localStorage.setItem(DB_KEY, JSON.stringify(this.data));
    } catch (e) {
      toast('保存失败：浏览器存储空间不足');
    }
  },
  export() {
    const blob = new Blob([JSON.stringify(this.data, null, 2)], { type: 'application/json' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = '消防学习知识库备份_' + new Date().toISOString().slice(0, 10) + '.json';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 300);
    toast('备份文件已导出，请妥善保管');
  },
  import(file, onDone) {
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const obj = JSON.parse(reader.result);
        if (!obj || typeof obj !== 'object') throw new Error('bad');
        this.data = Object.assign(this.default(), obj);
        this.save();
        toast('导入成功，页面已刷新');
        onDone ? onDone() : location.reload();
      } catch (e) {
        toast('导入失败：文件格式不正确');
      }
    };
    reader.readAsText(file);
  },
  reset() {
    this.data = this.default();
    this.save();
    toast('已清空全部学习数据');
  }
};

/* ---------------- 工具函数 ---------------- */
function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
function uid() { return Date.now().toString(36) + Math.random().toString(36).slice(2, 7); }
function fmtDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
}
function daysUntil(dateStr) {
  if (!dateStr) return null;
  const target = new Date(dateStr + 'T00:00:00');
  const today = new Date(); today.setHours(0, 0, 0, 0);
  return Math.round((target - today) / 86400000);
}
function toast(msg) {
  let el = document.getElementById('toast');
  if (!el) {
    el = document.createElement('div');
    el.id = 'toast';
    document.body.appendChild(el);
  }
  el.textContent = msg;
  el.classList.add('show');
  clearTimeout(el._t);
  el._t = setTimeout(() => el.classList.remove('show'), 2200);
}

