/* ---------- 渲染详细规范 ---------- */
function renderDetail(container){
  let totalClauses = 0;
  STANDARDS.forEach(s => s.chapters.forEach(c => totalClauses += c.clauses.length));

  let html = `
    <div class="std-toolbar">
      <div class="std-search-box">
        <span>🔍</span>
        <input type="text" id="stdDetailSearch" placeholder="搜索条文中的关键词（如：安全出口、防火间距、喷水强度…）">
      </div>
      <div class="std-toolbar-btns">
        <button class="btn btn-ghost btn-sm" id="stdExpandAll">📂 全部展开</button>
        <button class="btn btn-ghost btn-sm" id="stdCollapseAll">📁 全部折叠</button>
      </div>
    </div>
    <div class="std-stats-bar">
      <span>📚 共 <b>${STANDARDS.length}</b> 部规范</span>
      <span>📑 共 <b>${totalClauses}</b> 条条文</span>
      <span class="std-hint">点击规范编号展开章节，点击章节标题展开条文</span>
    </div>
    <div class="std-list" id="stdList">
  `;

  STANDARDS.forEach((std, si) => {
    const chapterCount = std.chapters.length;
    const clauseCount = std.chapters.reduce((n,c)=>n+c.clauses.length,0);
    html += `
      <div class="std-group" data-std-group="${si}" data-std-name="${esc(std.name)}" data-std-code="${esc(std.code)}">
        <button class="std-group-head" type="button">
          <span class="sgh-code">${esc(std.code)}</span>
          <span class="sgh-name">${esc(std.name)}</span>
          <span class="sgh-meta">
            ${std.mandatory?'<span class="sgh-badge must">全文强制</span>':'<span class="sgh-badge rec">推荐性</span>'}
            <span class="sgh-count">${chapterCount}章 · ${clauseCount}条</span>
            <span class="sgh-arrow">▼</span>
          </span>
        </button>
        <div class="std-group-body">
          <div class="std-desc">
            <div class="std-desc-line"><b>施行日期：</b>${esc(std.effective)}</div>
            <div class="std-desc-line">${esc(std.desc)}</div>
          </div>
    `;
    std.chapters.forEach((ch, ci) => {
      const cid = `std-${si}-ch-${ci}`;
      html += `
          <div class="std-chapter" data-chapter>
            <button class="std-chapter-head" type="button" data-toggle="${cid}">
              <span class="sch-arrow">▶</span>
              <span class="sch-title">${esc(ch.title)}</span>
              <span class="sch-count">${ch.clauses.length}条</span>
            </button>
            <div class="std-chapter-body" id="${cid}">
      `;
      ch.clauses.forEach(cl => {
        html += `
              <div class="clause-card${cl.mandatory?' mandatory':''}" data-clause data-search="${esc(cl.text.toLowerCase())}">
                <div class="cc-head">
                  <span class="cc-num">${esc(std.code.split('-')[0])} ${esc(cl.num)}</span>
                  ${cl.mandatory?'<span class="cc-tag must">强制条文</span>':'<span class="cc-tag rec">条文</span>'}
                </div>
                <div class="cc-text">${formatClause(cl.text)}</div>
              </div>
        `;
      });
      html += `
            </div>
          </div>
      `;
    });
    html += `
        </div>
      </div>
    `;
  });

  html += `</div>`;
  container.innerHTML = html;

  // 展开/折叠规范组
  container.querySelectorAll('.std-group-head').forEach(head=>{
    head.addEventListener('click', ()=>{
      const group = head.parentElement;
      group.classList.toggle('open');
    });
  });

  // 展开/折叠章节
  container.querySelectorAll('.std-chapter-head').forEach(head=>{
    head.addEventListener('click', ()=>{
      head.parentElement.classList.toggle('open');
    });
  });

  // 全部展开
  container.querySelector('#stdExpandAll').addEventListener('click', ()=>{
    container.querySelectorAll('.std-group, .std-chapter').forEach(el=>el.classList.add('open'));
  });
  // 全部折叠
  container.querySelector('#stdCollapseAll').addEventListener('click', ()=>{
    container.querySelectorAll('.std-group, .std-chapter').forEach(el=>el.classList.remove('open'));
  });

  // 搜索
  const searchInput = container.querySelector('#stdDetailSearch');
  searchInput.addEventListener('input', ()=>{
    const kw = searchInput.value.trim().toLowerCase();
    const groups = container.querySelectorAll('.std-group');
    if(!kw){
      groups.forEach(g=>{
        g.style.display='';
        g.querySelectorAll('.clause-card').forEach(c=>c.style.display='');
        g.querySelectorAll('.std-chapter').forEach(ch=>ch.classList.remove('open'));
      });
      return;
    }
    groups.forEach(g=>{
      let groupHas = false;
      g.querySelectorAll('.clause-card').forEach(c=>{
        const match = c.dataset.search.includes(kw);
        c.style.display = match ? '' : 'none';
        if(match) groupHas = true;
      });
      g.style.display = groupHas ? '' : 'none';
      if(groupHas){
        g.classList.add('open');
        g.querySelectorAll('.std-chapter').forEach(ch=>{
          const hasVisible = Array.from(ch.querySelectorAll('.clause-card')).some(c=>c.style.display!=='none');
          ch.classList.toggle('open', hasVisible);
        });
      }
    });
  });
}

