function esc(s){
  const d = document.createElement('div');
  d.textContent = s;
  return d.innerHTML;
}

/* ---------- 折叠面板 ---------- */
function initAccordions(root){
  (root||document).querySelectorAll('.acc-head').forEach(h => {
    h.onclick = () => h.parentElement.classList.toggle('open');
  });
}

/* ---------- 标签页 ---------- */
function initTabs(root){
  (root||document).querySelectorAll('.tabs').forEach(tabs => {
    const btns = tabs.querySelectorAll('.tab');
    btns.forEach(btn => {
      btn.onclick = () => {
        btns.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        const panel = document.getElementById(btn.dataset.tab);
        if(panel){
          panel.parentElement.querySelectorAll('.tab-panel').forEach(p => p.classList.remove('active'));
          panel.classList.add('active');
        }
      };
    });
  });
}

/* ---------- 搜索过滤 ---------- */
function initSearch(inputId, itemSelector, textGetter){
  const input = document.getElementById(inputId);
  if(!input) return;
  input.addEventListener('input', () => {
    const kw = input.value.trim().toLowerCase();
    document.querySelectorAll(itemSelector).forEach(el => {
      const text = textGetter ? textGetter(el) : el.textContent.toLowerCase();
      el.style.display = (!kw || text.includes(kw)) ? '' : 'none';
    });
  });
}

/* ---------- 回到顶部 ---------- */
function initBackTop(){
  const btn = document.createElement('button');
  btn.className = 'icon-btn';
  btn.id = 'backTop';
  btn.innerHTML = '⬆';
  btn.style.cssText = 'position:fixed;bottom:24px;right:24px;width:44px;height:44px;border-radius:50%;background:var(--grad-red);color:#fff;box-shadow:0 4px 14px rgba(200,16,46,.35);z-index:50;display:none;font-size:18px;border:none;cursor:pointer;';
  document.body.appendChild(btn);
  window.addEventListener('scroll', () => {
    btn.style.display = window.scrollY > 400 ? 'flex' : 'none';
  });
  btn.onclick = () => window.scrollTo({top:0,behavior:'smooth'});
}

/* ---------- 初始化 ---------- */
document.addEventListener('DOMContentLoaded', () => {
  renderSidebar();
  renderFooter();
  initBackTop();
  initAccordions();
  initTabs();
});

