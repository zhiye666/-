function initMiniQuiz(root){
  (root||document).querySelectorAll('[data-mini-quiz]').forEach(quizBox=>{
    const section = quizBox.dataset.miniQuiz;
    const questions = JSON.parse(quizBox.dataset.questions||'[]');
    let current = 0, score = 0, answered = false;
    const qEl = quizBox.querySelector('.mq-q');
    const optsEl = quizBox.querySelector('.mq-opts');
    const progEl = quizBox.querySelector('.mq-prog');
    const nextBtn = quizBox.querySelector('.mq-next');
    const resultEl = quizBox.querySelector('.mq-result');

    function renderQ(){
      if(current>=questions.length){ showResult(); return; }
      answered = false;
      const q = questions[current];
      if(progEl) progEl.textContent = `第 ${current+1}/${questions.length} 题`;
      if(qEl) qEl.textContent = q.q;
      optsEl.innerHTML = q.opts.map((o,i)=>`
        <button class="choice-btn" data-i="${i}">
          <span class="cb-letter">${'ABCD'[i]}</span>
          <span>${o}</span>
        </button>
      `).join('');
      optsEl.querySelectorAll('.choice-btn').forEach(btn=>{
        btn.onclick=()=>{
          if(answered) return;
          answered = true;
          const chosen = +btn.dataset.i;
          const correct = chosen===q.ans;
          if(correct) score++;
          optsEl.querySelectorAll('.choice-btn').forEach((b,i)=>{
            b.disabled = true;
            if(i===q.ans) b.classList.add('correct');
            if(i===chosen && !correct) b.classList.add('wrong');
          });
        };
      });
      if(nextBtn) nextBtn.style.display = 'block';
      if(resultEl) resultEl.style.display = 'none';
    }

    function showResult(){
      if(qEl) qEl.textContent = '';
      optsEl.innerHTML = '';
      if(nextBtn) nextBtn.style.display = 'none';
      const pct = Math.round(score/questions.length*100);
      const xpEarned = pct>=80?20:pct>=60?10:5;
      if(resultEl){
        resultEl.style.display = 'block';
        resultEl.innerHTML = `
          <div style="text-align:center;padding:20px;">
            <div style="font-size:48px;margin-bottom:10px;">${pct>=80?'🏆':pct>=60?'👍':'💪'}</div>
            <h3 style="margin-bottom:8px;">得分：${score}/${questions.length}（${pct}%）</h3>
            <p style="color:var(--ink-3);margin-bottom:8px;">${pct>=80?'掌握得很好！':pct>=60?'基本掌握，建议复习错题。':'需要加强学习，再试一次吧！'}</p>
            <p style="color:var(--gold);font-weight:700;margin-bottom:16px;">⚡ 获得 ${xpEarned} XP 经验值</p>
            <button class="btn btn-red" data-mq-retry>🔄 重新测试</button>
          </div>
        `;
        resultEl.querySelector('[data-mq-retry]').addEventListener('click',()=>{
          current = 0; score = 0;
          resultEl.style.display = 'none';
          if(nextBtn) nextBtn.style.display = 'block';
          renderQ();
        });
      }
      Progress.add(section, pct>=80?15:pct>=60?8:3);
      if(window.Game){
        Game.addQuizDone(questions.length);
        Game.addXP(xpEarned);
      }
    }

    if(nextBtn){
      nextBtn.addEventListener('click',()=>{
        if(!answered){ toast('请先选择一个答案','error'); return; }
        current++;
        renderQ();
      });
    }
    // 重试按钮
    const retryBtn = quizBox.querySelector('.mq-retry');
    if(retryBtn){
      retryBtn.style.display = 'none';
      retryBtn.addEventListener('click',()=>{
        current = 0; score = 0;
        retryBtn.style.display = 'none';
        renderQ();
      });
    }
    renderQ();
  });
}

