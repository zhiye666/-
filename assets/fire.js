function initSkillTree(root){
  const tree = (root||document).querySelector('#skilltree .roadmap');
  if(!tree) return;
  const steps = tree.querySelectorAll('.rm-step');
  if(!steps.length) return;

  const CP_KEY = 'fire_cp_cad';
  let done = {};
  try{ done = JSON.parse(localStorage.getItem(CP_KEY))||{}; }catch(e){}
  const cpDone = i => !!done['cad_'+i];

  // 状态：完成3个及以上实战关卡= mastered；完成1个= in-progress；否则 todo
  function levelState(i){
    const d = cpDone(i);
    const dPrev = i>0 && cpDone(i-1);
    if(d) return 'done';
    if(dPrev || i===0) return 'current';
    return 'todo';
  }

  function paint(){
    let doneCount = 0;
    steps.forEach((st,i)=>{
      const s = levelState(i);
      st.classList.remove('done','current');
      if(s==='done'){ st.classList.add('done'); doneCount++; }
      else if(s==='current') st.classList.add('current');
      const h = st.querySelector('h4');
      let chip = st.querySelector('.rm-state');
      if(!chip && h){ chip = document.createElement('span'); chip.className='tag rm-state'; h.appendChild(chip); }
      if(chip){
        if(s==='done'){ chip.textContent='已掌握 ✓'; chip.className='tag green rm-state'; }
        else if(s==='current'){ chip.textContent='当前阶段 →'; chip.className='tag rm-state'; }
        else { chip.textContent='待解锁'; chip.className='tag gray rm-state'; }
      }
    });
    // 顶部概览卡同步
    const statBox = document.querySelector('.stat-row .stat-box b');
    if(statBox) statBox.textContent = doneCount + '/' + steps.length + '级';
  }
  paint();

  // 实战关卡通过时重绘技能树
  const cpWrap = document.querySelector('[data-checkpoints="cad"]');
  if(cpWrap){
    const obs = new MutationObserver(paint);
    cpWrap.querySelectorAll('.checkpoint').forEach(cp=>obs.observe(cp,{attributes:true,attributeFilter:['class']}));
  }
}

