const Game = {
  key: 'fire_game_v1',
  data: null,

  levels: [
    {lv:1, name:'消防萌新', xp:0, icon:'🌱'},
    {lv:2, name:'初学入门', xp:50, icon:'📖'},
    {lv:3, name:'勤奋学员', xp:120, icon:'✏️'},
    {lv:4, name:'知识达人', xp:220, icon:'🎓'},
    {lv:5, name:'消防能手', xp:360, icon:'💪'},
    {lv:6, name:'业务骨干', xp:540, icon:'⭐'},
    {lv:7, name:'技术专家', xp:760, icon:'🏆'},
    {lv:8, name:'消防大师', xp:1040, icon:'👑'},
    {lv:9, name:'权威泰斗', xp:1400, icon:'🔥'},
    {lv:10,name:'传奇宗师', xp:2000, icon:'🌟'},
  ],

  achievements: [
    {id:'first_step', name:'启航', desc:'首次访问学习中心', icon:'🚀', cond:d=>d.visits>=1},
    {id:'first_xp', name:'初露锋芒', desc:'获得首个经验值', icon:'⚡', cond:d=>d.xp>=10},
    {id:'lv3', name:'小有所成', desc:'达到3级', icon:'📈', cond:d=>d.level>=3},
    {id:'lv5', name:'消防能手', desc:'达到5级', icon:'💪', cond:d=>d.level>=5},
    {id:'lv8', name:'消防大师', desc:'达到8级', icon:'👑', cond:d=>d.level>=8},
    {id:'streak3', name:'三天打鱼', desc:'连续学习3天', icon:'📅', cond:d=>d.streak>=3},
    {id:'streak7', name:'坚持不懈', desc:'连续学习7天', icon:'🔥', cond:d=>d.streak>=7},
    {id:'quiz10', name:'勤思好问', desc:'完成10道测验题', icon:'📝', cond:d=>(d.quizDone||0)>=10},
    {id:'all_sections', name:'博览群书', desc:'访问所有12个板块', icon:'📚', cond:d=>Object.keys(d.visited||{}).length>=12},
    {id:'notes5', name:'笔耕不辍', desc:'记录5条学习笔记', icon:'📒', cond:d=>(d.notesCount||0)>=5},
  ],

  load(){
    try{ this.data = JSON.parse(localStorage.getItem(this.key)) || {}; }catch(e){ this.data = {}; }
    if(!this.data.xp) this.data.xp = 0;
    if(!this.data.level) this.data.level = 1;
    if(!this.data.visited) this.data.visited = {};
    if(!this.data.achievements) this.data.achievements = [];
    if(!this.data.visits) this.data.visits = 0;
    if(!this.data.streak) this.data.streak = 1;
    if(!this.data.lastVisit) this.data.lastVisit = '';
    if(!this.data.quizDone) this.data.quizDone = 0;
    if(!this.data.notesCount) this.data.notesCount = 0;
  },

  save(){ localStorage.setItem(this.key, JSON.stringify(this.data)); },

  init(){
    this.load();
    this.trackVisit();
    this.calcLevel();
    this.renderXPWidget();
    this.checkAchievements();
    this.save();
  },

  trackVisit(){
    const today = new Date().toISOString().slice(0,10);
    if(this.data.lastVisit !== today){
      const yesterday = new Date(Date.now()-86400000).toISOString().slice(0,10);
      if(this.data.lastVisit === yesterday){
        this.data.streak = (this.data.streak||0) + 1;
      } else if(this.data.lastVisit && this.data.lastVisit !== today){
        this.data.streak = 1;
      }
      this.data.lastVisit = today;
    }
    this.data.visits = (this.data.visits||0) + 1;
    const cur = currentFile().replace('.html','');
    if(cur !== 'index'){
      this.data.visited[cur] = true;
    }
  },

  calcLevel(){
    let lv = 1;
    for(let i=this.levels.length-1; i>=0; i--){
      if(this.data.xp >= this.levels[i].xp){ lv = this.levels[i].lv; break; }
    }
    if(lv > this.data.level){
      this.data.level = lv;
      this.showLevelUp(lv);
    } else {
      this.data.level = lv;
    }
  },

  addXP(amount){
    this.load();
    this.data.xp += amount;
    this.calcLevel();
    this.checkAchievements();
    this.save();
    this.renderXPWidget();
  },

  addQuizDone(n){
    this.load();
    this.data.quizDone = (this.data.quizDone||0) + (n||1);
    this.addXP(n*5 || 5);
  },

  addNote(){
    this.load();
    this.data.notesCount = (this.data.notesCount||0) + 1;
    this.addXP(5);
  },

  getCurrentLevel(){
    const cur = this.levels.find(l=>l.lv===this.data.level) || this.levels[0];
    const next = this.levels.find(l=>l.lv===this.data.level+1);
    const baseXP = cur.xp;
    const nextXP = next ? next.xp : cur.xp + 500;
    const progress = next ? ((this.data.xp - baseXP) / (nextXP - baseXP)) * 100 : 100;
    return {cur, next, progress: Math.min(100, Math.max(0, progress)), xp:this.data.xp};
  },

  renderXPWidget(){
    const info = this.getCurrentLevel();
    const widget = document.getElementById('xpWidget');
    if(!widget) return;
    const nextLabel = info.next ? `${info.xp}/${info.next.xp} XP` : 'MAX';
    widget.innerHTML = `
      <div class="xp-level">${info.cur.lv}</div>
      <div class="xp-info">
        <div class="xp-label">${info.cur.icon} ${info.cur.name}</div>
        <div class="xp-bar"><div class="xp-bar-fill" style="width:${info.progress}%"></div></div>
        <div class="xp-num">${nextLabel}</div>
      </div>`;
  },

  showLevelUp(lv){
    const level = this.levels.find(l=>l.lv===lv);
    if(!level) return;
    const existing = document.querySelector('.level-up-toast');
    if(existing) existing.remove();
    const toast = document.createElement('div');
    toast.className = 'level-up-toast';
    toast.innerHTML = `
      <div class="lut-icon">${level.icon}</div>
      <h2>等级提升！</h2>
      <p>Lv.${lv} · ${level.name}</p>`;
    document.body.appendChild(toast);
    requestAnimationFrame(()=>{
      requestAnimationFrame(()=> toast.classList.add('show'));
    });
    setTimeout(()=>{
      toast.classList.remove('show');
      setTimeout(()=>toast.remove(), 400);
    }, 2500);
  },

  _checkingAchs: false,
  checkAchievements(){
    if(this._checkingAchs) return;
    this._checkingAchs = true;
    this.achievements.forEach(a=>{
      if(!this.data.achievements.includes(a.id) && a.cond(this.data)){
        this.data.achievements.push(a.id);
        this.addXP(15);
      }
    });
    this._checkingAchs = false;
  },

  renderAchievements(container){
    if(!container) return;
    container.innerHTML = this.achievements.map(a=>{
      const unlocked = this.data.achievements.includes(a.id);
      return `<div class="ach-badge ${unlocked?'unlocked':'locked'}">
        <div class="ab-icon">${unlocked?a.icon:'🔒'}</div>
        <h4>${a.name}</h4>
        <p>${a.desc}</p>
      </div>`;
    }).join('');
  }
};

/* ---------- 子分类标签页 ---------- */
function initSubTabs(root){
  (root||document).querySelectorAll('[data-sub-tabs]').forEach(group=>{
    const tabs = group.querySelectorAll('.sub-tab');
    const panels = document.querySelectorAll(`[data-sub-panel="${group.dataset.subTabs}"]`);
    const sidebarLinks = document.querySelectorAll('.doc-sidebar .ds-nav a[data-sidebar-tab]');
    function activate(targetName){
      tabs.forEach(t=>t.classList.toggle('active', t.dataset.subTarget===targetName));
      panels.forEach(p=>p.classList.toggle('active', p.dataset.subName===targetName));
      sidebarLinks.forEach(a=>a.classList.toggle('active', a.dataset.sidebarTab===targetName));
      window.scrollTo({top:0,behavior:'smooth'});
    }
    tabs.forEach(tab=>{
      tab.addEventListener('click', ()=>activate(tab.dataset.subTarget));
    });
    sidebarLinks.forEach(link=>{
      link.addEventListener('click', e=>{
        e.preventDefault();
        activate(link.dataset.sidebarTab);
      });
    });
  });
}

/* ---------- 侧边栏目录滚动高亮 ---------- */
function initSidebarTOC(){
  const sidebar = document.querySelector('.doc-sidebar');
  if(!sidebar) return;

  // 更新侧边栏学习进度
  function updateSidebarProgress(){
    const btns = document.querySelectorAll('[data-mark-read]');
    const fill = sidebar.querySelector('[data-sidebar-fill]');
    const label = sidebar.querySelector('[data-sidebar-progress]');
    if(!btns.length || !fill) return;
    let done = 0;
    btns.forEach(b=>{ if(b.classList.contains('done')) done++; });
    const pct = Math.round(done/btns.length*100);
    fill.style.width = pct+'%';
    if(label) label.textContent = pct+'%';
  }

  // 监听标记已学按钮，更新进度
  document.querySelectorAll('[data-mark-read]').forEach(btn=>{
    btn.addEventListener('click', ()=>setTimeout(updateSidebarProgress, 100));
  });
  updateSidebarProgress();

  const links = sidebar.querySelectorAll('.ds-nav a[href^="#"]');
  const sections = [];
  links.forEach(link=>{
    const id = link.getAttribute('href').slice(1);
    const el = document.getElementById(id);
    if(el) sections.push({link, el});
  });
  if(!sections.length) return;

  function onScroll(){
    let current = sections[0];
    sections.forEach(s=>{
      if(s.el.getBoundingClientRect().top <= 120) current = s;
    });
    links.forEach(l=>l.classList.remove('active'));
    if(current) current.link.classList.add('active');
  }
  window.addEventListener('scroll', onScroll, {passive:true});
  onScroll();
}

