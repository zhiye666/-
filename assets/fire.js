const Progress = {
  key: 'fire_progress_v2',
  data: null,
  load(){
    try{ this.data = JSON.parse(localStorage.getItem(this.key))||{}; }catch(e){ this.data={}; }
    return this.data;
  },
  save(){ localStorage.setItem(this.key, JSON.stringify(this.data)); },
  get(section){ return this.data[section]||0; },
  set(section, pct){ this.data[section]=Math.min(100,Math.max(0,pct)); this.save(); this.updateUI(); },
  add(section, delta){ this.set(section, this.get(section)+delta); },
  markRead(id){
    const read = this.data._read||(this.data._read={});
    if(!read[id]){ read[id]=1; this.save(); return true; }
    return false;
  },
  isRead(id){ return !!(this.data._read||{})[id]; },
  total(){
    const vals = Object.entries(this.data).filter(([k])=>!k.startsWith('_')).map(([,v])=>v);
    return vals.length ? Math.round(vals.reduce((a,b)=>a+b,0)/vals.length) : 0;
  },
  updateUI(){
    document.querySelectorAll('[data-progress]').forEach(el=>{
      const sec = el.dataset.progress;
      const pct = this.get(sec);
      const fill = el.querySelector('.po-bar-fill');
      const text = el.querySelector('.po-pct');
      if(fill) fill.style.width=pct+'%';
      if(text) text.textContent=pct+'%';
    });
    const totalEl = document.querySelector('[data-total-progress]');
    if(totalEl){
      const t = this.total();
      totalEl.textContent = t+'%';
      const ring = document.querySelector('.rp-fg');
      if(ring){ const c=2*Math.PI*52; ring.style.strokeDasharray=c; ring.style.strokeDashoffset=c*(1-t/100); }
    }
  }
};
Progress.load();

