function initQuiz(root){
  root = root || document;
  const quizEl = root.querySelector ? root.querySelector('[data-quiz]') : null;
  if(!quizEl) return;
  const allCats = ['全部', ...new Set(QUIZ_BANK.map(q=>q.cat))];
  let state = {
    mode: 'browse',   // browse | exam
    filter: '全部',
    answered: {},     // idx => selected opt index
    submitted: false,
    page: 0,
    perPage: 10
  };

  function getFiltered(){
    return state.filter==='全部' ? QUIZ_BANK : QUIZ_BANK.filter(q=>q.cat===state.filter);
  }

  function render(){
    const list = getFiltered();
    const totalPages = Math.max(1, Math.ceil(list.length/state.perPage));
    if(state.page>=totalPages) state.page=totalPages-1;
    const start = state.page*state.perPage;
    const pageList = list.slice(start, start+state.perPage);

    let catBtns = allCats.map(c=>`<button class="std-chip ${c===state.filter?'active':''}" data-cat="${c}">${c}</button>`).join('');
    let html = `
      <div style="display:flex;flex-wrap:wrap;gap:8px;margin-bottom:16px;">${catBtns}</div>
      <div style="display:flex;gap:8px;margin-bottom:16px;flex-wrap:wrap;">
        <button class="btn btn-primary" data-action="submit">📝 提交查看答案</button>
        <button class="btn btn-outline" data-action="reset">🔄 重置答题</button>
        <span style="margin-left:auto;align-self:center;color:var(--ink-3);font-size:13px;">共 ${list.length} 题 · 第 ${state.page+1}/${totalPages} 页</span>
      </div>
    `;

    pageList.forEach((q, i)=>{
      const realIdx = QUIZ_BANK.indexOf(q);
      const userAns = state.answered[realIdx];
      const isAns = state.submitted;
      html += `<div style="background:var(--side);border-radius:var(--radius);padding:16px;margin-bottom:12px;border:1px solid var(--line);">`;
      html += `<div style="font-weight:600;margin-bottom:10px;"><span style="color:var(--red);">${start+i+1}.</span> [${q.cat}] ${q.q}</div>`;
      q.opts.forEach((opt, oi)=>{
        let cls='quiz-opt';
        if(isAns){
          if(oi===q.ans) cls+=' correct';
          else if(oi===userAns) cls+=' wrong';
        } else if(oi===userAns){
          cls+=' selected';
        }
        const letter = ['A','B','C','D'][oi];
        html += `<label class="${cls}" data-qidx="${realIdx}" data-oidx="${oi}">
          <input type="radio" name="q${realIdx}" value="${oi}" ${oi===userAns?'checked':''} style="display:none;">
          <span class="quiz-letter">${letter}</span><span>${opt}</span>
        </label>`;
      });
      if(isAns){
        const correct = userAns===q.ans;
        html += `<div style="margin-top:8px;padding:8px 12px;border-radius:8px;font-size:13px;${correct?'background:#e6f9f0;color:#1a7f4e;':'background:#fef0f0;color:#c8102e;'}">
          ${correct?'✅ 回答正确':'❌ 回答错误'} · 正确答案：${['A','B','C','D'][q.ans]}<br>💡 ${q.explain||''}
        </div>`;
      }
      html += `</div>`;
    });

    // Pagination
    html += `<div style="display:flex;justify-content:center;gap:8px;margin-top:16px;">`;
    html += `<button class="btn btn-outline" data-page="prev" ${state.page===0?'disabled':''}>‹ 上一页</button>`;
    html += `<button class="btn btn-outline" data-page="next" ${state.page>=totalPages-1?'disabled':''}>下一页 ›</button>`;
    html += `</div>`;

    if(state.submitted){
      const correctCount = list.filter((q,idx)=>state.answered[QUIZ_BANK.indexOf(q)]===q.ans).length;
      const answeredCount = list.filter(q=>state.answered[QUIZ_BANK.indexOf(q)]!==undefined).length;
      const pct = list.length ? Math.round(correctCount/list.length*100) : 0;
      const grade = pct>=90?'优秀 🏆':pct>=75?'良好 👍':pct>=60?'及格 ✅':'需加强 📚';
      html += `<div style="margin-top:20px;padding:20px;background:var(--grad-red);color:#fff;border-radius:var(--radius-lg);text-align:center;">
        <div style="font-size:32px;font-weight:700;">${correctCount}/${list.length}</div>
        <div style="opacity:.9;margin-top:4px;">正确率 ${pct}% · ${grade}</div>
        <div style="opacity:.7;font-size:13px;margin-top:4px;">已答 ${answeredCount} 题</div>
      </div>`;
    }

    quizEl.innerHTML = html;

    // Bind events
    quizEl.querySelectorAll('.std-chip').forEach(btn=>{
      btn.onclick=()=>{ state.filter=btn.dataset.cat; state.page=0; state.submitted=false; state.answered={}; render(); };
    });
    quizEl.querySelectorAll('.quiz-opt').forEach(lbl=>{
      lbl.onclick=()=>{
        if(state.submitted) return;
        const qi = +lbl.dataset.qidx;
        const oi = +lbl.dataset.oidx;
        state.answered[qi] = oi;
        render();
      };
    });
    const submitBtn = quizEl.querySelector('[data-action="submit"]');
    if(submitBtn) submitBtn.onclick=()=>{ state.submitted=true; render(); window.scrollTo({top:quizEl.offsetTop-80,behavior:'smooth'}); };
    const resetBtn = quizEl.querySelector('[data-action="reset"]');
    if(resetBtn) resetBtn.onclick=()=>{ state.answered={}; state.submitted=false; render(); };
    const prevBtn = quizEl.querySelector('[data-page="prev"]');
    if(prevBtn) prevBtn.onclick=()=>{ if(state.page>0){state.page--;render();window.scrollTo({top:quizEl.offsetTop-80,behavior:'smooth'});} };
    const nextBtn = quizEl.querySelector('[data-page="next"]');
    if(nextBtn) nextBtn.onclick=()=>{ if(state.page<totalPages-1){state.page++;render();window.scrollTo({top:quizEl.offsetTop-80,behavior:'smooth'});} };
  }

  // Add quiz option styles
  if(!document.getElementById('quiz-styles')){
    const st = document.createElement('style');
    st.id='quiz-styles';
    st.textContent = `
      .quiz-opt{display:flex;align-items:center;gap:10px;padding:10px 14px;margin:4px 0;border-radius:8px;cursor:pointer;border:2px solid var(--line);background:#fff;transition:all .15s;}
      .quiz-opt:hover{border-color:var(--red-l);background:#fff7f7;}
      .quiz-opt.selected{border-color:var(--red);background:#fff0f0;}
      .quiz-opt.correct{border-color:#22a06b;background:#e6f9f0;}
      .quiz-opt.wrong{border-color:var(--red);background:#fef0f0;}
      .quiz-letter{display:inline-flex;align-items:center;justify-content:center;width:26px;height:26px;border-radius:50%;background:var(--side);font-weight:700;font-size:13px;flex-shrink:0;}
      .quiz-opt.selected .quiz-letter{background:var(--red);color:#fff;}
      .quiz-opt.correct .quiz-letter{background:#22a06b;color:#fff;}
      .quiz-opt.wrong .quiz-letter{background:var(--red);color:#fff;}
    `;
    document.head.appendChild(st);
  }

  render();
}

